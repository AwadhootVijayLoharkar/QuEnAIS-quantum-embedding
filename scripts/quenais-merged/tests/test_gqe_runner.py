def test_cli_solver_choices_come_from_the_registry():
    """One list, not three. The CLI and Config must never disagree."""
    parser = cli.build_parser()
    action = next(a for a in parser._actions if a.dest == "solver")
    assert set(action.choices) == set(SOLVERS)
    assert "gqe" in action.choices


