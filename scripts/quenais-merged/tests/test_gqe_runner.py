def _cfg(tmp_path, **kw):
    cfg = Config(molecule="LiH", basis="sto-3g", quantum_solver="gqe",
                 project_dir=str(tmp_path), **kw)
    return cfg.validate().make_dirs().load_geometry()


# ── Mandatory Hydra overrides ────────────────────────────────────────────

def test_command_carries_both_mandatory_overrides(tmp_path):
    """
    molecule=... and operator_pool.spec=... are both mandatory. Without the
    first, train.py silently loads n2.yaml and trains on N2 while the
    reported numbers claim to be yours.
    """
    cfg = _cfg(tmp_path)
    repo = tmp_path / "repo"
    repo.mkdir()
    (repo / "train.py").write_text("")

    cmd = gqe_runner.build_command(cfg, repo)
    joined = " ".join(cmd)
    assert "molecule=dmet_embedding" in joined
    assert "operator_pool.spec=dmet_excitation" in joined


def test_command_pins_the_step2_path_absolutely(tmp_path):
    """
    Belt and braces against the hardcoded path in the shipped yaml, which
    silently pointed at a stale directory.
    """
    cfg = _cfg(tmp_path)
    repo = tmp_path / "repo"
    repo.mkdir()
    (repo / "train.py").write_text("")

    cmd = gqe_runner.build_command(cfg, repo)
    match = [c for c in cmd if c.startswith("molecule.step2_pickle_path=")]
    assert len(match) == 1
    assert os.path.isabs(match[0].split("=", 1)[1])


